// Reads the worked examples shipped with the AI Architect plugin and writes data/worked-run.json,
// so every verdict, gate and count on /worked-run is read from the plugin's own files and its own
// contract check, never typed. Usage: node scripts/sync-worked-run.mjs [path/to/ai-architect]
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const site = join(dirname(fileURLToPath(import.meta.url)), '..')
const plugin = process.argv[2] ?? join(site, '..', '..', 'ai-architect')
const EXAMPLES = ['contract-rag', 'support-triage', 'personal-ai-coe']
const SOURCE = 'https://github.com/frankxai/ai-architect/tree/main/examples'

if (!existsSync(join(plugin, 'examples'))) {
  throw new Error(`No ai-architect checkout at ${plugin}. Pass its path as the first argument.`)
}

const plain = (s) => s.replace(/\*\*|`/g, '').replace(/\s*\n\s*/g, ' ').trim()

const sections = (md) =>
  Object.fromEntries(
    md
      .split(/^## /m)
      .slice(1)
      .map((s) => {
        const nl = s.indexOf('\n')
        return [s.slice(0, nl).trim().toLowerCase(), s.slice(nl + 1).replace(/Generated by AI Architect[^\n]*/, '').trim()]
      }),
  )

const firstParagraph = (text) => plain(text.split(/\n\s*\n/)[0])

function contractCheck(dir) {
  let out
  try {
    out = execFileSync(process.execPath, [join(plugin, 'scripts', 'check-artifacts.mjs'), dir], { encoding: 'utf8' })
  } catch (error) {
    out = error.stdout ?? ''
  }
  const m = out.match(/(\d+) checks, (\d+) pass, (\d+) fail/)
  if (!m) throw new Error(`check-artifacts printed no tally for ${dir}`)
  return { checks: Number(m[1]), pass: Number(m[2]), fail: Number(m[3]) }
}

function run(id) {
  const dir = join(plugin, 'examples', id, 'docs', 'architecture')
  const read = (rel) => readFileSync(join(dir, rel), 'utf8')
  const arch = JSON.parse(read('architecture.json'))
  const frame = sections(read('00-frame.md'))

  const receiptFile = readdirSync(join(dir, 'receipts')).find((f) => /^\d{4}-\d{2}-\d{2}-verify\.md$/.test(f))
  const tally = read(`receipts/${receiptFile}`).match(/(\d+) pointers, (\d+) CONFIRMED, (\d+) FAILED/)
  if (!tally) throw new Error(`${id}: receipt has no pointer tally`)

  const review = read('review.md')
  const title = review.match(/\*\*(F1 — [^*]+)\*\*/)
  if (!title) throw new Error(`${id}: review.md has no F1 finding`)
  const afterTitle = review.slice(review.indexOf(title[0]))
  const fix = [...afterTitle.split(/\*\*F2 — /)[0].matchAll(/^\d+\.\s+([\s\S]*?)(?=^\d+\.\s|^\s*$)/gm)].map((m) => plain(m[1]))

  return {
    id,
    name: arch.system_name,
    goal: arch.goal,
    generatedAt: arch.generated_at,
    fixtureNote: arch.fixture_note,
    source: `${SOURCE}/${id}/docs/architecture`,
    outcome: firstParagraph(frame['outcome']),
    killCriterion: firstParagraph(frame['kill criterion']),
    decisions: Object.entries(arch.decisions).map(([key, d]) => ({ id: key, verdict: d.verdict, evidence: plain(d.evidence) })),
    gates: Object.entries(arch.gates).map(([key, g]) => ({ id: key.replace(/^gate\./, ''), status: g.status, note: plain(g.evidence[0]) })),
    receipt: { file: receiptFile, pointers: Number(tally[1]), confirmed: Number(tally[2]), failed: Number(tally[3]) },
    finding: { title: plain(title[1]), fix },
    contract: contractCheck(dir),
  }
}

const out = {
  measuredAt: new Date().toISOString().slice(0, 10),
  pluginVersion: JSON.parse(readFileSync(join(plugin, 'package.json'), 'utf8')).version,
  licence: 'Apache-2.0',
  runs: EXAMPLES.map(run),
}
writeFileSync(join(site, 'data', 'worked-run.json'), JSON.stringify(out, null, 2) + '\n')
for (const r of out.runs) {
  const red = r.gates.filter((g) => g.status !== 'PASS').map((g) => g.id)
  console.log(`${r.id}: contract ${r.contract.pass}/${r.contract.checks} · pointers ${r.receipt.confirmed}/${r.receipt.pointers} · red: ${red.join(', ') || 'none'} · fix steps ${r.finding.fix.length}`)
}
