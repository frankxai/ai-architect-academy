// Reads the worked examples shipped with the AI Architect plugin and writes data/worked-run.json,
// so every verdict, gate and count on /worked-run is read from the plugin's own files and its own
// contract check, never typed. Usage: node scripts/sync-worked-run.mjs [path/to/ai-architect]
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const site = join(dirname(fileURLToPath(import.meta.url)), '..')
const plugin = process.argv[2] ?? join(site, '..', '..', 'ai-architect')
const EXAMPLES = ['contract-rag', 'support-triage', 'personal-ai-coe']
const FEATURED = 'contract-rag'
const SOURCE = 'https://github.com/frankxai/ai-architect/tree/main/examples'
const LIFECYCLE = ['frame', 'discovery', 'flow', 'decisions', 'economics', 'trust', 'evals', 'operate', 'verify']
const DECISIONS = ['model', 'loop', 'trust', 'run']
const STATUSES = new Set(['PASS', 'FAIL'])
const VERDICTS = new Set(['MADE', 'OPEN'])

if (!existsSync(join(plugin, 'examples'))) {
  throw new Error(`No ai-architect checkout at ${plugin}. Pass its path as the first argument.`)
}

const plain = (s) => s.replace(/\*\*|`/g, '').replace(/\s*\n\s*/g, ' ').trim()

const sections = (md) =>
  Object.fromEntries(
    md
      .split(/^## /m)
      .slice(1)
      .map((s) => {
        const nl = s.indexOf('\n')
        return [s.slice(0, nl).trim().toLowerCase(), s.slice(nl + 1).replace(/Generated by AI Architect[^\n]*/, '').trim()]
      }),
  )

const firstParagraph = (text) => plain(text.split(/\n\s*\n/)[0])

// The F1 finding's own numbered list: starts after the F1 line, ends at the list's end, the next
// finding, or the next heading. Tolerates a missing trailing newline and wrapped list items.
function finding(review, id) {
  const lines = review.split(/\r?\n/)
  const start = lines.findIndex((l) => /^\*\*F1 — /.test(l.trim()))
  if (start < 0) throw new Error(`${id}: review.md has no F1 finding`)
  const title = lines[start].trim().match(/^\*\*(F1 — [^*]+)\*\*/)
  if (!title) throw new Error(`${id}: F1 line is not a bold title`)
  const steps = []
  let sawBlank = false
  for (const line of lines.slice(start + 1)) {
    if (/^\*\*F\d+ — /.test(line.trim()) || /^#{1,6} /.test(line)) break
    if (line.trim() === '') {
      if (steps.length) sawBlank = true
      continue
    }
    const item = line.match(/^\d+\.\s+(.*)$/)
    if (item) {
      steps.push(item[1])
      sawBlank = false
    } else if (steps.length && !sawBlank && /^\s+\S/.test(line)) {
      steps[steps.length - 1] += ` ${line.trim()}`
    } else if (steps.length) {
      break
    }
  }
  if (!steps.length) throw new Error(`${id}: F1 has no numbered fix`)
  return { title: plain(title[1]), fix: steps.map(plain) }
}

function contractCheck(dir) {
  let out
  try {
    out = execFileSync(process.execPath, [join(plugin, 'scripts', 'check-artifacts.mjs'), dir], { encoding: 'utf8' })
  } catch (error) {
    out = error.stdout ?? ''
  }
  const m = out.match(/(\d+) checks, (\d+) pass, (\d+) fail/)
  if (!m) throw new Error(`check-artifacts printed no tally for ${dir}`)
  return { checks: Number(m[1]), pass: Number(m[2]), fail: Number(m[3]) }
}

function run(id) {
  const dir = join(plugin, 'examples', id, 'docs', 'architecture')
  const read = (rel) => readFileSync(join(dir, rel), 'utf8')
  const arch = JSON.parse(read('architecture.json'))
  const frame = sections(read('00-frame.md'))

  // The receipt is the one gate.verify cites, dated the day the run was generated, not merely the first file found.
  const receiptFile = `${arch.generated_at}-verify.md`
  const cited = (arch.gates['gate.verify']?.evidence ?? []).some((e) => e.includes(`receipts/${receiptFile}`))
  if (!cited || !existsSync(join(dir, 'receipts', receiptFile))) {
    throw new Error(`${id}: gate.verify does not cite an existing receipts/${receiptFile}`)
  }
  const tally = read(`receipts/${receiptFile}`).match(/(\d+) pointers, (\d+) CONFIRMED, (\d+) FAILED/)
  if (!tally) throw new Error(`${id}: receipt has no pointer tally`)

  return {
    id,
    name: arch.system_name,
    goal: arch.goal,
    generatedAt: arch.generated_at,
    fixture: arch.fixture === true,
    fixtureNote: arch.fixture_note,
    source: `${SOURCE}/${id}/docs/architecture`,
    outcome: firstParagraph(frame['outcome'] ?? ''),
    killCriterion: firstParagraph(frame['kill criterion'] ?? ''),
    decisions: Object.entries(arch.decisions).map(([key, d]) => ({ id: key, verdict: d.verdict, evidence: plain(d.evidence) })),
    gates: Object.entries(arch.gates).map(([key, g]) => ({ id: key.replace(/^gate\./, ''), status: g.status, note: plain(g.evidence[0]) })),
    receipt: { file: receiptFile, pointers: Number(tally[1]), confirmed: Number(tally[2]), failed: Number(tally[3]) },
    finding: finding(read('review.md'), id),
    contract: contractCheck(dir),
  }
}

function validate(r) {
  const bad = (msg) => {
    throw new Error(`${r.id}: ${msg}`)
  }
  if (r.gates.map((g) => g.id).join() !== LIFECYCLE.join()) bad(`gates are not the nine lifecycle gates in order`)
  for (const g of r.gates) if (!STATUSES.has(g.status)) bad(`gate ${g.id} has status ${g.status}`)
  if (r.decisions.map((d) => d.id).join() !== DECISIONS.join()) bad(`decisions are not model, loop, trust, run`)
  for (const d of r.decisions) if (!VERDICTS.has(d.verdict)) bad(`decision ${d.id} has verdict ${d.verdict}`)
  if (!r.fixture || !r.fixtureNote) bad('not marked as a fixture; the page presents every run as one')
  if (!r.outcome || !r.killCriterion) bad('frame has no outcome or kill criterion')
  if (r.receipt.confirmed + r.receipt.failed !== r.receipt.pointers) bad('receipt tally does not add up')
  return r
}

const runs = EXAMPLES.map(run).map(validate)
if (!runs.some((r) => r.id === FEATURED)) throw new Error(`featured run ${FEATURED} missing`)

const out = {
  measuredAt: new Date().toISOString().slice(0, 10),
  pluginVersion: JSON.parse(readFileSync(join(plugin, 'package.json'), 'utf8')).version,
  licence: 'Apache-2.0',
  featured: FEATURED,
  runs,
}
writeFileSync(join(site, 'data', 'worked-run.json'), JSON.stringify(out, null, 2) + '\n')
for (const r of runs) {
  const red = r.gates.filter((g) => g.status === 'FAIL').map((g) => g.id)
  console.log(`${r.id}: contract ${r.contract.pass}/${r.contract.checks} · pointers ${r.receipt.confirmed}/${r.receipt.pointers} · red: ${red.join(', ') || 'none'} · fix steps ${r.finding.fix.length}`)
}
